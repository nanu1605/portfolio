import { wcagContrast } from "culori";
import {
  colors,
  fonts,
  layout,
  motion,
  radius,
  type,
  type ContrastCheck,
  type Theme,
} from "../../src/styles/tokens";

type Palette = Record<string, Record<Theme, string>>;

const bothThemes: Theme[] = ["dark", "light"];

export function contrastFailures(palette: Palette, checks: ContrastCheck[]) {
  const failures: string[] = [];
  for (const { fg, bg, min, themes = bothThemes } of checks) {
    for (const theme of themes) {
      const ratio = wcagContrast(palette[fg][theme], palette[bg][theme]);
      if (ratio < min) {
        failures.push(
          `${theme}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`,
        );
      }
    }
  }
  return failures;
}

const block = (selector: string, lines: string[]) =>
  `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}`;

const themeVars = (theme: Theme) =>
  Object.entries(colors).map(([name, value]) => `--${name}: ${value[theme]};`);

export function renderTokensCss() {
  const [gutterBase, gutterMd, gutterLg] = layout.gutter;
  return [
    "/* Generated by `pnpm tokens:build` from src/styles/tokens.ts. Do not edit. */",
    block("@theme", [
      // Drop Tailwind's defaults so only these tokens exist as utilities.
      "--color-*: initial;",
      "--font-*: initial;",
      "--text-*: initial;",
      "--radius-*: initial;",
      "--ease-*: initial;",
      ...Object.entries(type).flatMap(
        ([name, [size, weight, tracking, leading]]) => [
          `--text-${name}: ${size};`,
          `--text-${name}--font-weight: ${weight};`,
          `--text-${name}--letter-spacing: ${tracking};`,
          `--text-${name}--line-height: ${leading};`,
        ],
      ),
      ...Object.entries(radius).map(
        ([name, value]) => `--radius-${name}: ${value};`,
      ),
      ...Object.entries(layout.container).map(
        ([name, value]) => `--container-${name}: ${value};`,
      ),
      `--spacing-section: ${layout.section};`,
      ...Object.entries(motion.ease).map(
        ([name, value]) => `--ease-${name}: ${value};`,
      ),
    ]),
    block("@theme inline", [
      `--font-sans: ${fonts.sans};`,
      `--font-mono: ${fonts.mono};`,
      ...Object.keys(colors).map((name) => `--color-${name}: var(--${name});`),
      "--spacing-gutter: var(--gutter);",
    ]),
    block(":root", [
      ...Object.entries(motion.duration).map(
        ([name, ms]) => `--duration-${name}: ${ms}ms;`,
      ),
      `--stagger: ${motion.stagger}ms;`,
      `--gutter: ${gutterBase};`,
    ]),
    `@media (min-width: 768px) {\n  :root {\n    --gutter: ${gutterMd};\n  }\n}`,
    `@media (min-width: 1024px) {\n  :root {\n    --gutter: ${gutterLg};\n  }\n}`,
    block(':root,\n[data-theme="dark"]', [
      "color-scheme: dark;",
      ...themeVars("dark"),
    ]),
    block('[data-theme="light"]', [
      "color-scheme: light;",
      ...themeVars("light"),
    ]),
    // Paper is light: printing (the resume, §8.10) forces the light tokens,
    // even inside regions pinned to dark (the hero).
    `@media print {\n${block(":root,\n[data-theme]", [
      "color-scheme: light;",
      ...themeVars("light"),
    ])
      .split("\n")
      .map((l) => `  ${l}`)
      .join("\n")}\n}`,
    "",
  ].join("\n\n");
}
